// Session-first regression: inventory, atomic definitions, canonical resolution and inert legacy policy.
import assert from "node:assert/strict";
import { mkdtemp, mkdir, writeFile, readFile, rm, symlink } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { tmpdir } from "node:os";
const temporary = await mkdtemp(join(tmpdir(), "loadout-session-first-"));
process.env.HOME = process.env.USERPROFILE = join(temporary, "home");
process.env.DSH_HOME = join(temporary, "dsh");
process.env.DSH_AGENTS_HOME = join(temporary, "agents");
process.env.DSH_CODEX_HOME = join(temporary, "codex");
const core = await import(process.env.DSH_LOADOUT_TEST_LIB ? pathToFileURL(join(process.env.DSH_LOADOUT_TEST_LIB, "core.js")) : "../lib/core.js");
const dsh = join(process.env.DSH_HOME, "skills");
const codex = join(process.env.DSH_CODEX_HOME, "skills");
const doc = (name, extra = "") => `---\nname: ${name}\ndescription: Test skill\n${extra}---\nBody\n`;
async function skill(root, name, text = doc(name)) {
  await mkdir(join(root, name), { recursive: true });
  await writeFile(join(root, name, "SKILL.md"), text);
}
const member = (name, root = "dsh") => ({ root, name });
const names = async (sessionId, options = {}) => (await core.sessionLoadoutView(sessionId, options)).effective.skills;
try {
  for (const name of ["alpha", "beta", "vanishing"]) await skill(dsh, name);
  await skill(dsh, "canonical-folder", doc("Canonical Name"));
  await skill(codex, "duplicate", doc("Canonical Name"));
  await skill(dsh, "broken", "No frontmatter\n");
  await skill(dsh, "bad-policy", doc("bad-policy", "user-invocable: maybe\n"));
  await skill(dsh, "no-channels", doc("no-channels", "disable-model-invocation: true\nuser-invocable: false\n"));
  const alphaBefore = await readFile(join(dsh, "alpha", "SKILL.md"), "utf8");
  assert.equal((await core.state()).summary.enabled, 0);
  assert.deepEqual((await core.listLoadouts()).migration, { manualReferences: [], hasLegacyPolicy: false });
  assert.equal((await core.importLegacyLoadout("Nothing")).code, "error.loadout.noLegacyReferences");
  assert.ok((await core.state()).summary.total >= 8, "installed inventory stays visible");
  assert.ok((await core.listProviderCandidates()).every((item) => !item.invocation.modelInvocable && !item.invocation.userInvocable));
  const a = (await core.createLoadout("A", "shared", [member("alpha")])).loadout;
  const b = (await core.createLoadout("B", null, [member("beta")])).loadout;
  await core.setSessionLoadout("session-a", a.id);
  await core.setSessionLoadout("session-b", b.id);
  assert.deepEqual(await names("session-a"), ["alpha"]);
  assert.deepEqual(await names("session-b"), ["beta"]);
  assert.deepEqual(await names("session-c"), []);
  assert.equal((await core.listLoadouts({ sessionId: "session-a" })).active, a.id);
  assert.equal((await core.state({ sessionId: "session-a" })).active, a.id);
  const candidate = (await core.listProviderCandidates({ sessionId: "session-a" })).find((item) => item.name === "alpha");
  assert.equal(candidate.invocation.modelInvocable, true, "selected native candidate overrides global blockers");
  const file = core.managerStatePath();
  const old = JSON.parse(await readFile(file, "utf8"));
  old.gatekeeper = false;
  old.sources.dsh = false;
  old.sources["retired-source"] = false;
  old.enabledSkills.dsh = ["beta"];
  old.enabledSkills["retired-source"] = ["missing"];
  old.disabledSkills.dsh = ["alpha", "beta"]; // conflicting legacy overrides are inert too
  old.activeLoadout = { user: b.id };
  old.disabledRoots = ["dsh"];
  await writeFile(file, JSON.stringify(old));
  const beforeGet = await readFile(file, "utf8");
  assert.deepEqual(await names("session-a"), ["alpha"], "legacy exclusions ignored");
  assert.deepEqual(await names("session-c"), [], "legacy enables, scope and gatekeeper ignored");
  const listing = await core.listLoadouts();
  assert.equal(listing.gatekeeper, true);
  assert.equal(listing.active, null);
  assert.equal(listing.migration.hasLegacyPolicy, true);
  assert.deepEqual(listing.migration.manualReferences, [member("beta"), member("missing", "retired-source")]);
  assert.equal(await readFile(file, "utf8"), beforeGet, "GET never writes");
  for (const task of [() => core.setSkillEnabled(dsh, "alpha", false), () => core.setSkillReferenced(dsh, "beta", true), () => core.setSourceEnabled("dsh", false), () => core.setCategoryEnabled("dsh", "*", false), () => core.setLoadoutEnabled(a.id, false), () => core.applyLoadout(a.id)]) assert.equal((await task()).code, "error.policy.sessionOnly");
  await assert.rejects(core.setGatekeeper(false), { code: "error.policy.sessionOnly" });
  assert.equal((await core.setSkillEnabled(dsh, "beta", true)).inventoryOnly, true, "repository install compatibility hook is inert");
  assert.equal(await readFile(file, "utf8"), beforeGet);
  const imported = (await core.importLegacyLoadout("Imported")).loadout;
  assert.deepEqual(imported.members, listing.migration.manualReferences);
  assert.deepEqual(await names("session-c"), [], "import never selects");
  const afterImport = JSON.parse(await readFile(file, "utf8"));
  for (const key of ["sources", "enabledSkills", "disabledSkills", "activeLoadout", "gatekeeper", "disabledRoots"]) assert.deepEqual(afterImport[key], old[key], `preserve legacy ${key}`);
  const full = [member("alpha"), member("vanishing"), member("broken"), member("bad-policy"), member("no-channels"), member("canonical-folder"), member("duplicate", "codex")];
  assert.ok((await core.updateLoadout(a.id, "A edited", "atomic", full)).loadout);
  assert.equal(resolve(join(dsh, "vanishing")), join(temporary, "dsh", "skills", "vanishing"));
  await rm(join(dsh, "vanishing"), { recursive: true });
  const view = await core.sessionLoadoutView("session-a");
  assert.deepEqual(view.effective.skills, ["alpha", "canonical-name"]);
  assert.equal(view.effective.members.find((item) => item.name === "vanishing").status, "missing");
  for (const name of ["broken", "bad-policy", "no-channels"]) assert.equal(view.effective.members.find((item) => item.name === name).status, "invalid");
  assert.equal(view.effective.members.find((item) => item.name === "duplicate").status, "shadowed");
  assert.ok(view.effective.members.filter((item) => item.status !== "available").every((item) => item.reason));
  const enabled = (await core.listProviderCandidates({ sessionId: "session-a" })).filter((item) => item.invocation.modelInvocable || item.invocation.userInvocable).map((item) => item.name).sort();
  assert.deepEqual([...view.effective.skills].sort(), enabled);
  assert.ok((await core.updateLoadout(a.id, "A retained", null, full)).loadout);
  const beforeFailure = await readFile(file, "utf8");
  assert.equal((await core.updateLoadout(a.id, "Must not persist", "changed", [...full, member("not-found")])).ok, false);
  assert.equal(await readFile(file, "utf8"), beforeFailure, "failed draft has no partial writes");
  assert.equal((await core.updateLoadout(a.id, "B", null, full)).code, "error.loadout.duplicate");
  assert.equal((await core.updateLoadout(a.id, "Bad", null, {})).code, "error.proto.invalidParams");
  assert.ok((await core.createLoadout("Copy", null, full, undefined, {}, a.id)).loadout);
  assert.equal((await core.createLoadout("Not copy", null, full)).ok, false);
  assert.equal((await core.createLoadout("Forged copy", null, [...full, member("new-missing")], undefined, {}, a.id)).ok, false);
  await symlink(join(dsh, "alpha"), join(codex, "alpha-link"), "dir");
  const linked = (await core.createLoadout("Linked", null, [member("alpha-link", "codex")])).loadout;
  await core.setSessionLoadout("linked-session", linked.id);
  assert.deepEqual(await names("linked-session"), ["alpha"]);
  assert.equal((await core.sessionLoadoutView("linked-session")).effective.members[0].status, "available");
  const project = join(temporary, "workspace");
  await mkdir(join(project, ".git"), { recursive: true });
  await skill(join(project, ".dsh", "skills"), "project-copy", doc("alpha"));
  const root = (await core.projectRoots([project])).find((item) => item.kind === "project-dsh");
  assert.equal((await core.createLoadout("Project rejected", null, [member("project-copy", root.key)], undefined, {projectCwds:[project]})).code, 'error.loadout.globalOnly');
  const projectLoadout = (await core.createLoadout("Global and project", null, [member("alpha")], undefined, { projectCwds: [project] })).loadout;
  await core.setSessionLoadout("project-session", projectLoadout.id);
  const projectView = await core.sessionLoadoutView("project-session", { projectCwds: [project] });
  assert.deepEqual(projectView.effective.skills, ["alpha"]);
  assert.equal(projectView.effective.members.find((item) => item.root === "dsh").status, "shadowed");
  assert.equal((await core.state({ sessionId: "project-session", projectCwds: [project] })).summary.enabled, 1);
  assert.equal((await core.listProviderCandidates({ sessionId: "project-session", cwd: project })).find((item) => item.name === "alpha").locator.rootKey, root.key);
  await core.setSessionLoadout("session-a", "");
  assert.equal((await core.sessionLoadoutView("session-a")).loadoutId, null);
  assert.deepEqual(await names("session-a"), []);
  assert.equal((await core.getProviderSkill(candidate, { sessionId: "session-a" })).invocation.modelInvocable, false, "cached candidate policy refreshed");
  await core.setSessionLoadout("session-a", a.id);
  await core.setSessionLoadout("session-a", null);
  assert.deepEqual(await names("session-a"), []);
  await core.deleteLoadout(b.id);
  assert.deepEqual(await names("session-b"), []);
  assert.equal(JSON.parse(await readFile(file, "utf8")).activeLoadout.user, b.id, "legacy defaults read-only even on deletion");
  assert.equal(await readFile(join(dsh, "alpha", "SKILL.md"), "utf8"), alphaBefore);
  await writeFile(file, "invalid JSON");
  assert.deepEqual(await names("session-a"), []);
  assert.equal((await core.updateLoadout(a.id, "Safe", null, [])).code, "error.state.invalid");
  console.log("session-first loadout core ok");
} finally {
  assert.ok(temporary.startsWith(join(tmpdir(), "loadout-session-first-")));
  await rm(temporary, { recursive: true, force: true });
}
